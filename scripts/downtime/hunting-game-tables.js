const ordinary = [22, 18, 15, 15, 12, 8, 7, 3];
const exceptional = [8, 7, 10, 15, 18, 17, 15, 10];
export function defaultHuntingGame(terrainId) {
  const rows = animals[terrainId.replace("biome-", "")];
  if (!rows) throw new Error(`Missing hunting table for ${terrainId}.`);
  return rows.map(([name, foodMin, foodMax], i) => ({
    name,
    foodMin,
    foodMax,
    size: i < 4 ? "Small" : i < 6 ? "Medium" : "Large",
    ac: i < 4 ? 13 : 12,
    ordinary: ordinary[i],
    exceptional: exceptional[i],
  }));
}
